/**
 * Solar Power & Photovoltaic Flux
 *
 * Implements the inverse-square law of solar irradiance, atmospheric optical depth,
 * solar panel efficiency, dust obscuration, and day/night illumination cycles.
 *
 * Reference: NASA Solar Constant (SORCE / TSIS-1 TIM instrument): S0 = 1361 W/m^2
 * NASA Glenn Research Center "Photovoltaic Power Systems for Space"
 */

import type { SolarFluxResult } from "../../types/physics";

export const SOLAR_CONSTANT_EARTH_1AU = 1361.0; // W/m^2 (TSIS-1 baseline)

/**
 * Calculates solar irradiance (flux) at an arbitrary heliocentric distance in AU.
 * Follows the inverse-square law: S(r) = S0 / r^2
 *
 * @param distanceAU Distance from Sun in Astronomical Units (AU)
 * @returns Solar flux in Watts per square meter (W/m^2)
 */
export function calculateSolarFlux(distanceAU: number): number {
  if (distanceAU <= 0) throw new Error("Distance must be greater than zero");
  return SOLAR_CONSTANT_EARTH_1AU / Math.pow(distanceAU, 2);
}

/**
 * Calculates effective electrical power generated by a solar array.
 * Formula: P = S(r) * Area * Efficiency * cos(ZenithAngle) * Transmittance * (1 - Dust)
 *
 * @param distanceAU Heliocentric distance in AU
 * @param areaM2 Solar panel surface area in m^2
 * @param efficiency Photovoltaic conversion efficiency (e.g. 0.30 for triple-junction GaAs)
 * @param sunZenithAngleDeg Angle between surface normal and sun (0 = directly overhead, 90 = horizon)
 * @param opticalDepthTau Atmospheric optical depth (0 in vacuum of Moon, ~0.5 nominal Mars, >2 in dust storms)
 * @param dustObscurationFraction Surface dust layer covering panels (0.0 to 1.0)
 * @returns Detailed SolarFluxResult object with power output in Watts
 */
export function calculateSolarArrayOutput(
  distanceAU: number,
  areaM2: number,
  efficiency: number = 0.30,
  sunZenithAngleDeg: number = 0,
  opticalDepthTau: number = 0,
  dustObscurationFraction: number = 0
): SolarFluxResult {
  const solarFluxWPerM2 = calculateSolarFlux(distanceAU);

  // If sun is below horizon, no direct illumination
  if (sunZenithAngleDeg >= 90) {
    return {
      distanceAU,
      solarFluxWPerM2,
      effectivePowerOutputWatts: 0,
      sunZenithAngleDeg,
      atmosphericTransmittance: 0,
      dustObscurationFactor: dustObscurationFraction,
    };
  }

  const zenithRad = (sunZenithAngleDeg * Math.PI) / 180;
  const cosZenith = Math.cos(zenithRad);

  // Beer-Lambert law for atmospheric attenuation: T = exp(-tau / cos(theta))
  const atmosphericTransmittance = opticalDepthTau > 0 
    ? Math.exp(-opticalDepthTau / Math.max(0.01, cosZenith))
    : 1.0;

  const dustFactor = Math.max(0, 1.0 - Math.min(1.0, dustObscurationFraction));

  const effectivePowerOutputWatts =
    solarFluxWPerM2 *
    areaM2 *
    efficiency *
    cosZenith *
    atmosphericTransmittance *
    dustFactor;

  return {
    distanceAU,
    solarFluxWPerM2,
    effectivePowerOutputWatts: Math.max(0, effectivePowerOutputWatts),
    sunZenithAngleDeg,
    atmosphericTransmittance,
    dustObscurationFactor: dustObscurationFraction,
    simplification: "Simplified for gameplay: geometric inverse-square irradiance and Beer-Lambert atmospheric extinction. Does not simulate ray-traced regional crater rim topographic self-shadowing penumbras in real time.",
  };
}

/**
 * Calculates illumination fraction for specific landing sites.
 *
 * @param siteId Location ID (e.g., 'shackleton_rim', 'lunar_equator', 'jezero')
 * @param missionDay Mission elapsed time in days
 * @returns Illumination fraction between 0.0 (total darkness) and 1.0 (full sun)
 */
export function getSiteIlluminationFraction(siteId: string, missionDay: number): number {
  if (siteId.toLowerCase().includes("shackleton")) {
    // Shackleton crater rim South Pole experiences 86%-92% near-continuous light
    // with brief dips as crater peaks cast seasonal shadows
    const shadowDip = Math.sin((missionDay / 29.53) * 2 * Math.PI);
    return shadowDip < -0.8 ? 0.2 : 0.90;
  }

  if (siteId.toLowerCase().includes("lunar") || siteId.toLowerCase().includes("moon")) {
    // Standard lunar synodic day = 29.53 Earth days (14.75 days light, 14.75 days dark)
    const phase = ((missionDay % 29.53) / 29.53) * 2 * Math.PI;
    const cosAngle = Math.cos(phase);
    return cosAngle > 0 ? cosAngle : 0;
  }

  if (siteId.toLowerCase().includes("jezero") || siteId.toLowerCase().includes("mars")) {
    // Mars sol = 24.66 hours (~1.027 Earth days)
    const solFraction = (missionDay % 1.027) / 1.027;
    const sunAngle = Math.sin(solFraction * 2 * Math.PI);
    return sunAngle > 0 ? sunAngle : 0;
  }

  return 1.0;
}
