/**
 * Core Physics Types for Outpost: Beyond Earth
 * All units follow SI standard: meters (m), kilograms (kg), seconds (s), Watts (W), Joules (J), Sieverts (Sv)
 */

export interface OrbitalElements {
  semiMajorAxisAU: number; // Astronomical Units
  semiMajorAxisKm: number;
  orbitalPeriodDays: number;
  eccentricity: number;
  inclinationDeg: number;
}

export interface HohmannTransferResult {
  originBody: string;
  targetBody: string;
  transferSemiMajorAxisAU: number;
  transferTimeDays: number;
  transferTimeSeconds: number;
  deltaV1HeliocentricKmS: number; // Departure burn relative to circular heliocentric orbit
  deltaV2HeliocentricKmS: number; // Arrival burn relative to circular heliocentric orbit
  totalDeltaVKmS: number; // Total heliocentric transfer delta-v
  transInjectionDeltaVKmS: number; // Trans-Injection burn from LEO/Parking orbit
  synodicPeriodDays: number; // Launch window interval
  simplification?: string; // Model simplification note for Engineer's Panel
}

export interface RocketStage {
  name: string;
  dryMassKg: number;
  propellantMassKg: number;
  ispSeaLevelS: number;
  ispVacuumS: number;
  thrustVacuumN: number;
}

export interface RocketConfiguration {
  id: string;
  name: string;
  stages: RocketStage[];
  maxPayloadToLEOKg: number;
  costPerLaunchMUSD: number;
}

export interface SolarFluxResult {
  distanceAU: number;
  solarFluxWPerM2: number; // W/m^2
  effectivePowerOutputWatts: number; // Power generated by panel
  sunZenithAngleDeg: number;
  atmosphericTransmittance: number; // 0 to 1
  dustObscurationFactor: number; // 0 to 1
  simplification?: string;
}

export interface RadiationDoseResult {
  unshieldedDoseRateMSvPerDay: number;
  shieldedDoseRateMSvPerDay: number;
  attenuationFraction: number; // percentage of radiation stopped
  regolithShieldingThicknessCm: number;
  cumulativeDoseMSv: number;
  isSolarParticleEvent: boolean;
  speIntensityMultiplier: number;
  simplification?: string;
}

export interface LifeSupportDemand {
  crewCount: number;
  durationDays: number;
  oxygenRequiredKg: number;
  waterRequiredKg: number;
  dryFoodRequiredKg: number;
  co2ProducedKg: number;
  waterRecycledKg: number;
  netWaterConsumedKg: number;
  simplification?: string;
}

export interface ThermalBalanceResult {
  ambientTempKelvin: number;
  internalTempKelvin: number;
  radiativeLossWatts: number;
  conductiveLossWatts: number;
  heatingPowerRequiredWatts: number;
  coolingPowerRequiredWatts: number;
  simplification?: string;
}

export interface CommsDelayResult {
  distanceKm: number;
  oneWayLightTimeSeconds: number;
  oneWayLightTimeMinutes: number;
  roundTripLightTimeSeconds: number;
  signalStrengthFactor: number; // Inverse-square attenuation factor
}
